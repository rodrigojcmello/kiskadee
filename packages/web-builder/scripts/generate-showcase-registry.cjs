#!/usr/bin/env node
/**
 * Generate Next.js showcase registries from @kiskadee/web-builder manifests.
 *
 * This script reads metadata produced by the web-builder (one manifest.json
 * per preset under packages/web-builder/build/**) and generates TypeScript
 * registries under packages/showcase/registry:
 *
 *   - templates.registry.generated.ts
 *   - css.registry.generated.ts
 *
 * These files are then re-exported by the hand-written registry modules so
 * that the showcase automatically picks up any new presets without manual
 * updates.
 */

const fs = require('node:fs');
const fsp = require('node:fs/promises');
const path = require('node:path');

// When this script lived at the monorepo root, __dirname already pointed to
// the repo root and we could resolve "packages/web-builder/build" directly.
// After moving the script to packages/web-builder/scripts, we must:
// - treat the web-builder package root as the source base (build directory),
// - and still resolve the showcase registry target relative to the monorepo root.

// packages/web-builder/scripts -> packages/web-builder
const webBuilderRoot = __dirname ? path.resolve(__dirname, '..') : process.cwd();

// Source of manifests: packages/web-builder/build
const webBuilderBuildDir = path.resolve(webBuilderRoot, 'build');

// Monorepo root: packages/web-builder -> ../.. -> <repoRoot>
const repoRoot = path.resolve(webBuilderRoot, '..', '..');

// Base URL used by the Next.js app to serve build artifacts
const showcaseBuildBase = '/build';

// Target directory for generated registries in the showcase app
// NOTE: The registry now lives at packages/showcase/registry (outside app/)
const showcaseRegistryDir = path.resolve(repoRoot, 'packages', 'showcase', 'registry');

/** @typedef {{
 *   key: string;
 *   displayName: string;
 *   author: string | null;
 *   schemaName: string | null;
 *   version: [number, number, number] | null;
 *   segments: string[];
 *   themes: Record<string, string[]>;
 * }} Manifest
 */

async function existsDir(dir) {
  try {
    const stat = await fsp.stat(dir);
    return stat.isDirectory();
  } catch {
    return false;
  }
}

async function discoverManifests() {
  if (!(await existsDir(webBuilderBuildDir))) {
    console.error('[generate-showcase-registry] Build directory not found:', webBuilderBuildDir);
    console.error(
      'Make sure you have run the @kiskadee/web-builder build beforehand (run-build.ts).'
    );
    process.exitCode = 1;
    return [];
  }

  const entries = await fsp.readdir(webBuilderBuildDir, { withFileTypes: true });

  /** @type {Manifest[]} */
  const manifests = [];

  for (const entry of entries) {
    if (!entry.isDirectory()) continue;
    const dir = path.join(webBuilderBuildDir, entry.name);
    const manifestPath = path.join(dir, 'manifest.json');
    if (!fs.existsSync(manifestPath)) continue;

    try {
      const raw = await fsp.readFile(manifestPath, 'utf8');
      /** @type {Manifest} */
      const parsed = JSON.parse(raw);
      if (!parsed || typeof parsed.key !== 'string') continue;
      manifests.push(parsed);
    } catch (e) {
      console.warn('[generate-showcase-registry] Failed to read manifest for', entry.name, e);
    }
  }

  return manifests;
}

function generateTemplatesRegistrySource(manifests) {
  const lines = [];

  lines.push('// AUTO-GENERATED FILE. DO NOT EDIT MANUALLY.');
  lines.push(
    '// Generated by scripts/generate-showcase-registry.cjs based on web-builder manifests.'
  );
  lines.push(
    "import type { ComponentClassNameMap, ExtraArtifactsJSON } from '@kiskadee/web-builder/types';"
  );
  lines.push('');
  lines.push('type ClassNamesModuleLike = { default: ComponentClassNameMap };');
  lines.push('');
  lines.push('// Helper that wraps fetch and returns a "module-like" object compatible');
  lines.push('// with the existing code in app/providers.tsx.');
  lines.push('function loadJsonModule(path: string): Promise<ClassNamesModuleLike> {');
  lines.push('  return fetch(path)');
  lines.push('    .then((response) => {');
  lines.push('      if (!response.ok) {');
  lines.push(
    '        throw new Error(`Failed to load classNamesMap JSON: ${path} (${response.status})`);'
  );
  lines.push('      }');
  lines.push('      return response.json();');
  lines.push('    })');
  lines.push('    .then((json) => ({ default: json as ComponentClassNameMap }));');
  lines.push('}');
  lines.push('');
  lines.push('// Helper to load extra.<segment>.<theme>.kiskadee.json files with proper typing.');
  lines.push('function loadExtraJson(path: string): Promise<ExtraArtifactsJSON> {');
  lines.push('  return fetch(path)');
  lines.push('    .then((response) => {');
  lines.push('      if (response.status === 404) {');
  lines.push(
    '        // Extra artifacts are optional; treat 404 as "no extras" and return an empty object.'
  );
  lines.push('        return {} as ExtraArtifactsJSON;');
  lines.push('      }');
  lines.push('      if (!response.ok) {');
  lines.push(
    '        throw new Error(`Failed to load extra JSON: ${path} (${response.status})`);'
  );
  lines.push('      }');
  lines.push('      return response.json() as Promise<ExtraArtifactsJSON>;');
  lines.push('    });');
  lines.push('}');
  lines.push('');

  // coreMaps
  lines.push('export const coreMaps = {');
  for (const m of manifests) {
    const corePath = `${showcaseBuildBase}/${m.key}/core.kiskadee.json`;
    lines.push(`  '${m.key}': () => loadJsonModule('${corePath}'),`);
  }
  lines.push('} as const;');
  lines.push('');

  // paletteMaps
  lines.push('export const paletteMaps = {');
  for (const m of manifests) {
    for (const segment of m.segments || []) {
      const themes = m.themes?.[segment];
      if (!themes || !themes.length) continue;
      for (const theme of themes) {
        const key = `${m.key}|${segment}|${theme}`;
        const file = `${segment}.${theme}.kiskadee.json`;
        const url = `${showcaseBuildBase}/${m.key}/${file}`;
        lines.push(`  '${key}': () => loadJsonModule('${url}'),`);
      }
    }
  }
  lines.push('} as const;');
  lines.push('');

  // extraMaps: maps designSystem|segment|theme to loader of extra.<segment>.<theme>.kiskadee.json
  lines.push('export const extraMaps = {');
  for (const m of manifests) {
    for (const segment of m.segments || []) {
      const themes = m.themes?.[segment];
      if (!themes || !themes.length) continue;
      for (const theme of themes) {
        const key = `${m.key}|${segment}|${theme}`;
        const file = `extra.${segment}.${theme}.kiskadee.json`;
        // Only generate an entry if the corresponding extra JSON file
        // actually exists in the web-builder build output. This avoids
        // issuing fetch requests that would 404 for design systems that
        // don't define extra artifacts for a given segment/theme.
        const physicalPath = path.join(webBuilderBuildDir, m.key, file);
        if (!fs.existsSync(physicalPath)) continue;
        const url = `${showcaseBuildBase}/${m.key}/${file}`;
        lines.push(`  '${key}': () => loadExtraJson('${url}'),`);
      }
    }
  }
  lines.push('} as const;');
  lines.push('');

  // paletteIndex
  lines.push('export const paletteIndex = {');
  for (const m of manifests) {
    const segs = m.segments || [];
    const themesBySegmentEntries = [];
    for (const seg of segs) {
      const themes = m.themes?.[seg] || [];
      if (!themes.length) continue;
      const themesList = themes.map((t) => `'${t}'`).join(', ');
      themesBySegmentEntries.push(`      ${JSON.stringify(seg)}: [${themesList}]`);
    }

    lines.push(`  '${m.key}': {`);
    lines.push(`    segments: [${segs.map((s) => `'${s}'`).join(', ')}],`);
    if (themesBySegmentEntries.length) {
      lines.push('    themesBySegment: {');
      lines.push(themesBySegmentEntries.join(',\n'));
      lines.push('    }');
    } else {
      lines.push('    themesBySegment: {}');
    }
    lines.push('  },');
  }
  lines.push('} as const;');
  lines.push('');

  // designSystemMeta
  lines.push('export const designSystemMeta = {');
  for (const m of manifests) {
    const displayName = m.displayName || m.key;
    lines.push(`  '${m.key}': { displayName: ${JSON.stringify(displayName)} },`);
  }
  lines.push('} as const;');
  lines.push('');

  return lines.join('\n');
}

function generateCssRegistrySource(manifests) {
  const lines = [];

  lines.push('// AUTO-GENERATED FILE. DO NOT EDIT MANUALLY.');
  lines.push(
    '// Generated by scripts/generate-showcase-registry.cjs based on web-builder manifests.'
  );
  lines.push('');
  lines.push('export const cssPaths = {');
  for (const m of manifests) {
    const coreCss = `${showcaseBuildBase}/${m.key}/core.kiskadee.css`;
    const effectsCss = `${showcaseBuildBase}/${m.key}/effects.kiskadee.css`;

    lines.push(`  '${m.key}': {`);
    lines.push(`    core: '${coreCss}',`);
    lines.push(`    effects: '${effectsCss}',`);
    lines.push('    palettes: {');

    for (const segment of m.segments || []) {
      const themes = m.themes?.[segment] || [];
      for (const theme of themes) {
        const paletteKey = `${segment}|${theme}`;
        const file = `${segment}.${theme}.kiskadee.css`;
        const url = `${showcaseBuildBase}/${m.key}/${file}`;
        lines.push(`      '${paletteKey}': '${url}',`);
      }
    }

    lines.push('    }');
    lines.push('  },');
  }
  lines.push('} as const;');
  lines.push('');
  lines.push('export type CssRegistry = typeof cssPaths;');
  lines.push('');

  return lines.join('\n');
}

async function writeFileIfChanged(targetPath, content) {
  let existing = null;
  try {
    existing = await fsp.readFile(targetPath, 'utf8');
  } catch {
    // ignore
  }

  if (existing === content) return;

  await fsp.mkdir(path.dirname(targetPath), { recursive: true });
  await fsp.writeFile(targetPath, content, 'utf8');
  console.log('[generate-showcase-registry] Wrote', path.relative(repoRoot, targetPath));
}

async function main() {
  const manifests = await discoverManifests();
  if (!manifests.length) {
    console.warn('[generate-showcase-registry] No manifests found under', webBuilderBuildDir);
    return;
  }

  const templatesTs = generateTemplatesRegistrySource(manifests);
  const cssTs = generateCssRegistrySource(manifests);

  const templatesTarget = path.resolve(showcaseRegistryDir, 'design-systems.registry.generated.ts');
  const cssTarget = path.resolve(showcaseRegistryDir, 'css.registry.generated.ts');

  await writeFileIfChanged(templatesTarget, templatesTs);
  await writeFileIfChanged(cssTarget, cssTs);
}

main().catch((err) => {
  console.error('[generate-showcase-registry] Unexpected error:', err);
  process.exitCode = 1;
});
